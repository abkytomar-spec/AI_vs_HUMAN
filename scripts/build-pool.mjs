// Builds src/data/pool.generated.ts from dataset/pool.json.
// - validates every entry and checks that both image sizes exist in public/images
// - sorts images by their opaque id so file order says nothing about origin
// - encodes the result (see src/lib/poolCodec.ts) so labels are not plain text
// Usage: node scripts/build-pool.mjs [--check]
import fs from 'node:fs/promises';
import path from 'node:path';

const KEY = 'real-or-rendered';
const root = path.resolve(import.meta.dirname, '..');
const check = process.argv.includes('--check');

function encode(json) {
  const bytes = new TextEncoder().encode(json);
  const out = Buffer.alloc(bytes.length);
  for (let i = 0; i < bytes.length; i++) out[i] = bytes[i] ^ KEY.charCodeAt(i % KEY.length) ^ ((i * 31) % 251);
  return out.toString('base64');
}

const datasetPath = process.argv.find((a) => a.endsWith('.json')) ?? 'dataset/pool.json';
const dataset = JSON.parse(await fs.readFile(path.join(root, datasetPath), 'utf8'));
const problems = [];
const images = [];
for (const item of dataset.images) {
  if (!item.id) {
    problems.push(`${item.key}: not normalized yet (no id)`);
    continue;
  }
  for (const w of [480, 800]) {
    try {
      await fs.access(path.join(root, 'public/images', `${item.id}-${w}.jpg`));
    } catch {
      problems.push(`${item.key}: missing public/images/${item.id}-${w}.jpg`);
    }
  }
  const required = ['alt', 'group', 'category', 'origin', 'note', 'title', 'pageUrl', 'author', 'license', 'provenance'];
  for (const field of required) if (!item[field]) problems.push(`${item.key}: missing ${field}`);
  if (item.origin === 'ai' && !item.difficulty) problems.push(`${item.key}: AI image without difficulty`);
  images.push({
    id: item.id,
    alt: item.alt,
    category: item.category,
    group: item.group,
    origin: item.origin,
    ...(item.origin === 'ai' ? { difficulty: item.difficulty } : {}),
    note: item.note,
    clues: item.clues ?? [],
    noReliableTell: Boolean(item.noReliableTell),
    source: {
      title: item.title,
      pageUrl: item.pageUrl,
      author: item.author,
      license: item.license,
      ...(item.licenseUrl ? { licenseUrl: item.licenseUrl } : {}),
      ...(item.generator ? { generator: item.generator } : {}),
      ...(item.camera ? { camera: item.camera } : {}),
      ...(item.date ? { date: item.date } : {}),
      provenance: item.provenance,
    },
  });
}

const groups = new Map();
for (const img of images) {
  const g = groups.get(img.group) ?? { ai: 0, human: 0 };
  g[img.origin === 'ai' ? 'ai' : 'human']++;
  groups.set(img.group, g);
}
for (const [name, g] of groups) if (g.ai > 0 && g.human < 2) problems.push(`group ${name}: ${g.human} photographs, need at least 2`);

if (problems.length) {
  console.error(`Pool has ${problems.length} problem(s):\n- ` + problems.join('\n- '));
  process.exit(1);
}

images.sort((a, b) => a.id.localeCompare(b.id));
const pool = { version: dataset.version, images };
const counts = images.reduce((acc, i) => ((acc[i.origin === 'ai' ? `ai:${i.difficulty}` : 'human'] = (acc[i.origin === 'ai' ? `ai:${i.difficulty}` : 'human'] ?? 0) + 1), acc), {});
console.log(`Pool ${dataset.version}: ${images.length} images, ${groups.size} groups`, counts);

if (!check) {
  const out = `// Generated by scripts/build-pool.mjs from dataset/pool.json. Do not edit by hand.\n// Lightly encoded so answers are not plain text in the bundle (obfuscation, not security).\nexport const POOL = ${JSON.stringify(encode(JSON.stringify(pool)))};\n`;
  await fs.writeFile(path.join(root, 'src/data/pool.generated.ts'), out);
  console.log('Wrote src/data/pool.generated.ts');
}
